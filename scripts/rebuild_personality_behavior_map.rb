def render_specification(indentation, specification)
  nested = "#{indentation}  "
  profile = "#{nested}  "
  lines = ["#{indentation}specification:"]
  lines << "#{nested}construct_definition: #{JSON.generate(specification.fetch(:construct_definition))}"
  lines << "#{nested}activation_context: #{JSON.generate(specification.fetch(:activation_context))}"
  %i[low_profile high_profile].each do |direction|
    lines << "#{nested}#{direction}:"
    specification.fetch(direction).each do |field, value|
      if value.is_a?(Array)
        lines << "#{profile}#{field}:"
        value.each do |item|
          lines << "#{profile}  - #{JSON.generate(item)}"
        end
      else
        lines << "#{profile}#{field}: #{JSON.generate(value)}"
      end
    end
    if direction == :low_profile
      lines << "#{nested}neutral_tendency: #{JSON.generate(specification.fetch(:neutral_tendency))}"
    end
  end
  lines << "#{nested}band_calibrations:"
  specification.fetch(:band_calibrations).each do |band_id, calibration|
    lines << "#{profile}#{band_id}: #{JSON.generate(calibration)}"
  end
  lines << "#{nested}contextual_modifiers:"
  specification.fetch(:contextual_modifiers).each do |field, value|
    lines << "#{profile}#{field}: #{JSON.generate(value)}"
  end
  lines << "#{nested}non_implications:"
  specification.fetch(:non_implications).each do |item|
    lines << "#{nested}  - #{JSON.generate(item)}"
  end
  lines.join("\n")
end

def render_band_description(specification, band)
  case band.fetch("direction")
  when "low"
    behavior = specification.fetch(:low_profile)
  when "high"
    behavior = specification.fetch(:high_profile)
  when "neutral"
    behavior = {
      internal_tendency: specification.fetch(:neutral_tendency),
      attention_and_judgment: "本项不单独提高低向或高向信息的权重，按当前事实和直接问题判断。",
      observable_expression: "不需要为了展示中间分数制造固定措辞或额外内容。",
      decision_and_interaction: "本项不单独加速、推迟或补全决定与互动，由实际情境决定。",
      workplace_manifestations: ["当前为中间区间，不预设低向或高向的固定行为信号。"]
    }
  else
    raise "unknown personality direction: #{band.fetch("direction")}"
  end

  marker = "【#{band.fetch("min_score")}–#{band.fetch("max_score")}｜#{band.fetch("label")}】"
  sections = []
  sections << marker
  sections << [
    "【本档人格解释】",
    specification.fetch(:construct_definition),
    band.fetch("band_explanation")
  ].join("\n\n")
  sections << [
    "【本档行为表现】",
    "* 触发场景：#{specification.fetch(:activation_context)}",
    "* 内部倾向：#{behavior.fetch(:internal_tendency)}",
    "* 注意与判断：#{behavior.fetch(:attention_and_judgment)}",
    "* 可观察外显：#{behavior.fetch(:observable_expression)}",
    "* 决策与互动：#{behavior.fetch(:decision_and_interaction)}",
    "* 强度呈现：#{band.fetch("intensity_guidance")}"
  ].join("\n")
  sections << (["【本档具体线索】"] + behavior.fetch(:workplace_manifestations).map { |item| "* #{item}" }).join("\n")
  calibration = specification.fetch(:band_calibrations).fetch(band.fetch("id").to_sym)
  sections << ["【本档特有校准】", "* #{calibration}"].join("\n")
  sections << [
    "【情境调节】",
    "* 更容易显现：#{specification.fetch(:contextual_modifiers).fetch(:more_visible_when)}",
    "* 较少显现：#{specification.fetch(:contextual_modifiers).fetch(:less_visible_when)}"
  ].join("\n")
  sections << (["【禁止推论】"] + specification.fetch(:non_implications).map { |item| "* #{item}" }).join("\n")
  sections.join("\n\n")
end

def render_band_descriptions(indentation, specification, score_bands)
  nested = "#{indentation}  "
  content = "#{nested}  "
  lines = [
    "#{indentation}# GENERATED：由 specification 与 score_bands 确定性生成，请勿单独手改。",
    "#{indentation}band_descriptions:"
  ]
  score_bands.each do |band|
    lines << "#{nested}#{band.fetch("id")}: |-"
    render_band_description(specification, band).split("\n", -1).each do |line|
      lines << (line.empty? ? "" : "#{content}#{line}")
    end
  end
  lines.join("\n")
end

path = ARGV.fetch(0, "backend/business_config/personality_behavior_map.yaml")
parsed = YAML.load_file(path)
score_bands = parsed.fetch("score_bands")
trait_ids = []
parsed.fetch("dimensions").each do |dimension_id, dimension|
  trait_ids << dimension_id
  dimension.fetch("facets").each_key do |facet_id|
    trait_ids << "#{dimension_id}.#{facet_id}"
  end
end

unless trait_ids == SPECS.keys
  raise "trait specification order mismatch: #{trait_ids.inspect}"
end

raw = File.read(path)
raw.sub!(/^version: .*$/, "version: personality-behavior-map-v18-specific-facet-bands")
index = 0
rewritten = raw.gsub(/^([ ]+)(?:band_descriptions|specification):\n.*?^\1section_start:/m) do
  indentation = Regexp.last_match(1)
  trait_id = trait_ids.fetch(index)
  index += 1
  specification = SPECS.fetch(trait_id)
  [
    render_specification(indentation, specification),
    render_band_descriptions(indentation, specification, score_bands),
    "#{indentation}section_start:"
  ].join("\n")
end

raise "expected #{trait_ids.length} band blocks, replaced #{index}" unless index == trait_ids.length

File.write(path, rewritten)
