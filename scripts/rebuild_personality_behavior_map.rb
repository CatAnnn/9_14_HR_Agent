def spec(construct, activation, low, neutral, high, boundary)
  {
    construct_definition: construct,
    activation_context: activation,
    low_profile: {
      internal_tendency: low.fetch(0),
      attention_and_judgment: low.fetch(1),
      observable_expression: low.fetch(2),
      decision_and_interaction: low.fetch(3)
    },
    neutral_tendency: neutral,
    high_profile: {
      internal_tendency: high.fetch(0),
      attention_and_judgment: high.fetch(1),
      observable_expression: high.fetch(2),
      decision_and_interaction: high.fetch(3)
    },
    interpretation_boundary: boundary
  }
end

def detail(low, high, more_visible_when, less_visible_when)
  {
    low: low,
    high: high,
    contextual_modifiers: {
      more_visible_when: more_visible_when,
      less_visible_when: less_visible_when
    }
  }
end

def split_non_implications(boundary)
  boundary
    .split(/[；。]/)
    .map(&:strip)
    .reject(&:empty?)
    .map { |item| "#{item}。" }
end

